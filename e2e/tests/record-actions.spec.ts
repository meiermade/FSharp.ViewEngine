import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

test('bulk deletion confirms, cancels, persists per workspace and restores the demo @cross-browser', async ({ page, browser, baseURL }) => {
  await page.goto('/examples/application/transactions?account=101&status=verified&filters=account,status&sort=date-asc')
  await page.locator('html').evaluate(el => el.dataset.recordActionDocument = 'retained')
  const payment = page.getByRole('checkbox', { name: 'Select Client payment', exact: true })
  const hosting = page.getByRole('checkbox', { name: 'Select Cloud hosting', exact: true })
  await payment.check(); await hosting.check()
  await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Delete 2 transactions?', exact: true })
  await expect(dialog).toBeVisible()
  await expect(dialog).toContainText('Client payment')
  await expect(dialog).toContainText('Cloud hosting')
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(payment).toBeChecked(); await expect(hosting).toBeChecked()
  await expect(page.getByRole('button', { name: 'Delete selected', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.locator('[data-fve-notification]').getByRole('status')).toContainText('2 transactions deleted')
  await expect(page.locator('html')).toHaveAttribute('data-record-action-document', 'retained')
  await expect(payment).toHaveCount(0); await expect(hosting).toHaveCount(0)
  await expect(page.locator('[data-ledger-selection-toolbar]')).toBeHidden()
  for (const [key, value] of Object.entries({ account: '101', status: 'verified', sort: 'date-asc' })) {
    expect(new URL(page.url()).searchParams.get(key)).toBe(value)
  }
  expect(new Set(new URL(page.url()).searchParams.get('filters')!.split(','))).toEqual(new Set(['account', 'status']))
  await page.reload()
  await expect(payment).toHaveCount(0)
  await expect(page.locator('[data-fve-notification]')).toHaveCount(0)
  await page.goto('/examples/application/accounts/101')
  await expect(page.getByRole('definition').filter({ hasText: '$20,555.00' })).toBeVisible()
  await page.goto('/examples/application/transactions?ledger=jordan')
  await expect(payment).toBeVisible()
  await page.goto('/examples/application/transactions?ledger=alex')
  await expect(payment).toHaveCount(0)
  const other = await browser.newContext({ baseURL })
  try {
    const fresh = await other.newPage()
    await fresh.goto('/examples/application/transactions')
    await expect(fresh.getByRole('checkbox', { name: 'Select Client payment', exact: true })).toBeVisible()
  } finally { await other.close() }
  const session = (await page.context().cookies()).find(cookie => cookie.name.startsWith('fve-ledger-'))!
  expect(session.httpOnly).toBe(true)
  expect(session.expires).toBe(-1)
  await page.getByRole('button', { name: 'Restore records', exact: true }).click()
  await expect(payment).toBeVisible(); await expect(hosting).toBeVisible()
  await expect(page.locator('[data-fve-notification]').getByRole('status')).toContainText('Records restored')
})

test('account group selection submits records and blocked batches delete nothing @cross-browser', async ({ page }) => {
  await page.goto('/examples/application/accounts')
  const assets = page.getByRole('checkbox', { name: 'Select Assets', exact: true })
  await assets.check()
  await expect(page.locator('[data-ledger-selection-toolbar]')).toContainText('3 selected')
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  const checking = page.getByRole('checkbox', { name: 'Select Operating checking', exact: true })
  const unused = page.getByRole('checkbox', { name: 'Select Unassigned expense', exact: true })
  await checking.check(); await unused.check()
  await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
  const blocked = page.getByRole('dialog', { name: 'Delete 2 accounts?', exact: true })
  await expect(blocked).toContainText('Nothing was deleted')
  await expect(blocked.getByRole('button', { name: 'Delete', exact: true })).toBeDisabled()
  await blocked.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(checking).toBeChecked(); await expect(unused).toBeChecked()
  await checking.uncheck()
  await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
  const allowed = page.getByRole('dialog', { name: 'Delete 1 account?', exact: true })
  expect((await new AxeBuilder({ page }).include('dialog[open]').analyze()).violations).toEqual([])
  await allowed.getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.locator('[data-fve-notification]').getByRole('status')).toContainText('1 account deleted')
  await expect(unused).toHaveCount(0)
  await expect(checking).toBeVisible()
  await page.getByRole('button', { name: 'Restore records', exact: true }).click()
  await expect(unused).toBeVisible()
  await page.goto('/examples/application/accounts?search=Unassigned')
  await unused.check()
  await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
  await page.getByRole('dialog', { name: 'Delete 1 account?', exact: true }).getByRole('button', { name: 'Delete', exact: true }).click()
  await expect(page.getByText('No matching accounts', { exact: true })).toBeVisible()
  await expect(page.locator('[data-ledger-selection-toolbar]')).toBeHidden()
  await page.getByRole('button', { name: 'Restore records', exact: true }).click()
  await expect(unused).toBeVisible()
  expect(new URL(page.url()).searchParams.get('search')).toBe('Unassigned')
})

test('native forms support confirmation, cancellation and deletion without JavaScript', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, javaScriptEnabled: false })
  try {
    const page = await context.newPage()
    await page.goto('/examples/application/transactions?sort=date-asc')
    const payment = page.getByRole('checkbox', { name: 'Select Client payment', exact: true })
    const hosting = page.getByRole('checkbox', { name: 'Select Cloud hosting', exact: true })
    await payment.check(); await hosting.check()
    await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
    const confirmation = page.getByRole('region', { name: 'Delete 2 transactions?', exact: true })
    await expect(confirmation).toBeVisible()
    await confirmation.getByRole('button', { name: 'Cancel', exact: true }).click()
    await expect(payment).toBeChecked(); await expect(hosting).toBeChecked()
    await page.getByRole('button', { name: 'Delete selected', exact: true }).click()
    await confirmation.getByRole('button', { name: 'Delete', exact: true }).click()
    const feedback = page.getByRole('region', { name: 'Collection notifications', exact: true })
    await expect(feedback.getByRole('status')).toContainText('2 transactions deleted')
    await expect(payment).toHaveCount(0); await expect(hosting).toHaveCount(0)
    expect(new URL(page.url()).searchParams.get('sort')).toBe('date-asc')
    await feedback.getByRole('link', { name: 'Dismiss 2 transactions deleted', exact: true }).click()
    await expect(feedback.getByRole('status')).toHaveCount(0)
    await page.reload()
    await expect(feedback.getByRole('status')).toHaveCount(0)
    await page.getByRole('button', { name: 'Restore records', exact: true }).click()
    await expect(feedback.getByRole('status')).toContainText('Records restored')
    await expect(payment).toBeVisible()
    await expect(page.getByRole('button', { name: 'Restore records', exact: true })).toBeDisabled()
  } finally { await context.close() }
})

test('row-action hover, open and keyboard focus stay distinct on collection rows @cross-browser', async ({ page, browserName }) => {
  for (const colorScheme of ['light', 'dark'] as const) {
    await page.emulateMedia({ colorScheme })
    for (const [kind, record] of [['accounts', 'Unassigned expense'], ['transactions', 'Office supplies']]) {
      await page.goto(`/examples/application/${kind}`)
      const trigger = page.getByRole('button', { name: `Actions for ${record}`, exact: true })
      const row = trigger.locator('xpath=ancestor::tr')
      for (const selected of [false, true]) {
        const choice = row.getByRole('checkbox', { name: `Select ${record}`, exact: true })
        await choice.setChecked(selected)
        await page.mouse.move(0, 0)
        const idle = await trigger.evaluate(button => getComputedStyle(button).backgroundImage)
        await trigger.hover()
        const hover = await trigger.evaluate(button => getComputedStyle(button).backgroundImage)
        expect(hover).not.toBe(idle)
        await page.mouse.down()
        expect(await trigger.evaluate(button => getComputedStyle(button).backgroundImage)).not.toBe(hover)
        await page.mouse.move(0, 0)
        await page.mouse.up()
        await expect(trigger).toHaveAttribute('aria-expanded', 'false')
      }
      await trigger.click()
      await expect(trigger).toHaveAttribute('aria-expanded', 'true')
      await page.mouse.move(0, 0)
      expect(await trigger.evaluate(button => getComputedStyle(button).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
      await page.keyboard.press('Escape')
      await expect(trigger).toBeFocused()
      await row.getByRole('link').last().focus()
      await page.keyboard.press(browserName === 'webkit' ? 'Alt+Tab' : 'Tab')
      await expect(trigger).toBeFocused()
      await expect(trigger).toHaveCSS('outline-style', 'solid')
      await trigger.evaluate(button => { (button as HTMLButtonElement).disabled = true })
      await trigger.hover({ force: true })
      await expect(trigger).toHaveCSS('background-image', 'none')
      await expect(trigger).toBeDisabled()
    }
  }
})

test('row-action component recipes open real actions and copy their complete composition @cross-browser', async ({ page }) => {
  const viewport = page.viewportSize()!
  for (const component of ['button', 'dropdown-menu', 'table']) {
    await page.goto(`/components/${component}`)
    const region = page.locator(`#components-${component}-row-actions`)
    const trigger = region.getByRole('button', { name: 'Actions for Unassigned expense', exact: true })
    await trigger.click()
    const menu = page.getByRole('menu', { name: 'Actions for Unassigned expense', exact: true })
    await expect(menu.getByRole('menuitem', { name: 'Open account', exact: true })).toHaveAttribute('href', '/examples/application/accounts/105')
    await expect(menu.getByRole('menuitem', { name: 'Delete account', exact: true })).toBeEnabled()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await region.getByRole('tab', { name: 'Code', exact: true }).click()
    await expect(region.locator('pre')).toContainText('let rowActionMenu')
    await expect(region.locator('pre')).toContainText('fveDropdownMenuTrigger')
    await expect(region.locator('pre')).toContainText('fveButton')
    await region.getByRole('tab', { name: 'Preview', exact: true }).click()
    await page.setViewportSize({ width: 320, height: 1000 })
    await page.locator('html').evaluate(el => el.style.fontSize = '200%')
    await trigger.hover()
    await trigger.click()
    await expect(menu).toBeVisible()
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.setViewportSize(viewport)
  }
})

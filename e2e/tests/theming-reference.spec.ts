import { test, expect } from '@playwright/test'

test('Theming exposes supported overrides with scoped light and dark examples @cross-browser', async ({ page }) => {
  await page.goto('/guides/theming')
  const reference = page.locator('#theme-token-reference')
  await expect(reference.locator('[data-css-token]')).toHaveCount(10)
  await expect(page.getByRole('heading', { name: 'Internal variables', exact: true })).toBeVisible()
  const names = await page.locator('[data-css-token]').evaluateAll(es => es.map(e => e.getAttribute('data-css-token')!))
  expect(names.some(name => name.startsWith('--fve-internal-'))).toBe(false)
  const scoped = page.locator('#theming-scoped-controls')
  const action = scoped.getByRole('button', { name: 'Save changes', exact: true })
  const radius = await page.locator('body').evaluate(el => getComputedStyle(el).getPropertyValue('--fve-radius-control'))
  for (const mode of ['light', 'dark']) {
    await page.evaluate(mode => (window as any).fveColorMode.set(mode), mode)
    await expect(action).toHaveCSS('border-top-left-radius', '12px')
    await action.hover()
    await expect(action).toHaveCSS('background-color', mode === 'light' ? 'rgb(22, 101, 52)' : 'rgb(52, 211, 153)')
    expect(await page.locator('body').evaluate(el => getComputedStyle(el).getPropertyValue('--fve-radius-control'))).toBe(radius)
  }
  const example = scoped.locator('xpath=ancestor::fve-example')
  await example.getByRole('tab', { name: 'Code', exact: true }).click()
  await expect(example.getByRole('tabpanel', { name: 'Code', exact: true })).toContainText('--fve-primary-hover:light-dark(')
})

test('CSS reference filters and pages locally with URL history @cross-browser', async ({ page }) => {
  await page.goto('/guides/theming?tokenGroup=actions')
  const reference = page.locator('#theme-token-reference')
  const rows = reference.locator('[data-css-token]')
  const pages = reference.getByRole('navigation', { name: 'CSS variable pages' })
  await expect(reference.getByRole('status')).toHaveText('1–10 of 70 variables')
  await expect(rows).toHaveCount(10)
  const first = await rows.evaluateAll(es => es.map(e => e.getAttribute('data-css-token')))
  await pages.getByRole('link', { name: 'Next', exact: true }).scrollIntoViewIfNeeded()
  await page.evaluate(() => { (window as any).tokenArticle = document.getElementById('main-content') })
  const scrollTop = await page.locator('[data-docs-main]').evaluate(el => el.scrollTop)
  await pages.getByRole('link', { name: 'Next', exact: true }).click()
  await expect(reference.getByRole('status')).toHaveText('11–20 of 70 variables')
  expect(new URL(page.url()).searchParams.get('tokenPage')).toBe('2')
  await expect.poll(() => page.locator('[data-docs-main]').evaluate(el => el.scrollTop)).toBe(scrollTop)
  expect(await page.evaluate(() => (window as any).tokenArticle === document.getElementById('main-content'))).toBe(true)
  expect(await rows.evaluateAll(es => es.map(e => e.getAttribute('data-css-token')))).not.toEqual(first)
  const search = reference.getByRole('searchbox', { name: 'Search CSS variables' })
  await search.fill('--FVE-PRIMARY-')
  await expect(reference.getByRole('status')).toHaveText('1–10 of 10 variables')
  await expect(search).toBeFocused()
  expect(new URL(page.url()).searchParams.has('tokenPage')).toBe(false)
  expect(await rows.evaluateAll(es => es.every(e => e.getAttribute('data-css-token')?.startsWith('--fve-primary-')))).toBe(true)
  await page.goBack()
  await expect(reference.getByRole('status')).toHaveText('11–20 of 70 variables')
  await page.goForward()
  await expect(reference.getByRole('status')).toHaveText('1–10 of 10 variables')
  await reference.getByRole('link', { name: 'Clear filters', exact: true }).click()
  await expect(search).toHaveValue('')
  await reference.getByRole('combobox', { name: 'Variable group', exact: true }).click()
  await page.getByRole('option', { name: 'Component overrides', exact: true }).click()
  await expect(reference.getByRole('status')).toHaveText('1–10 of 12 variables')
  await expect(reference.getByRole('rowheader', { name: '--fve-table-row-hover', exact: true })).toHaveCount(1)
  await search.fill('no-such-variable')
  await expect(reference.getByRole('status')).toHaveText('0–0 of 0 variables')
  await expect(reference.getByRole('table')).toContainText('No variables match.')
  await expect(rows).toHaveCount(0)
  await expect(pages.getByRole('link', { name: 'Next', exact: true })).toHaveCount(0)
  await page.reload()
  await expect(search).toHaveValue('no-such-variable')
  await expect(reference.getByRole('table')).toContainText('No variables match.')
})

test('The CSS reference supports search, filters and pagination without JavaScript', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, javaScriptEnabled: false })
  const page = await context.newPage()
  await page.goto('/guides/theming?tokenGroup=actions')
  const reference = page.locator('#theme-token-reference')
  await expect(reference.getByRole('table', { name: 'CSS variables', exact: true })).toBeVisible()
  await reference.getByRole('link', { name: 'Next', exact: true }).click()
  await expect(reference.getByRole('status')).toHaveText('11–20 of 70 variables')
  await reference.getByRole('combobox', { name: 'Variable group', exact: true }).selectOption('components')
  await reference.getByRole('searchbox', { name: 'Search CSS variables' }).fill('sticky')
  await reference.getByRole('button', { name: 'Apply', exact: true }).click()
  await expect(reference.getByRole('status')).toHaveText('1–1 of 1 variables')
  await expect(reference.getByRole('rowheader', { name: '--fve-table-row-hover', exact: true })).toBeVisible()
  await context.close()
})

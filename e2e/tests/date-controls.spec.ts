test('Compact selection supports dropdown captions and trigger-adjacent picker placement @cross-browser', async ({ page }) => {
  await page.setViewportSize({ width: 1280, height: 900 })
  await page.goto('/components/month-calendar')
  const captionCalendar = page.locator('#components-month-calendar-caption-panel-preview').locator('#birth-month-calendar')
  const year = captionCalendar.getByRole('combobox', { name: 'Year', exact: true })
  const month = captionCalendar.getByRole('combobox', { name: 'Month', exact: true })
  await year.selectOption('1920')
  await month.selectOption('01')
  await expect(captionCalendar.getByRole('button', { name: 'Previous month', exact: true })).toBeDisabled()
  const firstMonthDay = captionCalendar.getByRole('gridcell', { name: 'Thursday, January 15, 1920', exact: true })
  await firstMonthDay.press('PageUp')
  await expect(year).toHaveValue('1920')
  await expect(month).toHaveValue('01')
  await expect(firstMonthDay).toBeFocused()
  await year.selectOption('2026')
  await month.selectOption('12')
  const finalMonthDay = captionCalendar.getByRole('gridcell', { name: 'Tuesday, December 15, 2026', exact: true })
  await finalMonthDay.press('PageDown')
  await expect(year).toHaveValue('2026')
  await expect(month).toHaveValue('12')
  await expect(finalMonthDay).toBeFocused()
  await year.selectOption('1990')
  await month.selectOption('02')
  await expect(captionCalendar.getByRole('heading', { name: 'February 1990', exact: true })).toBeAttached()
  const presentation = await captionCalendar.evaluate(element => {
    const style = getComputedStyle(element)
    return { padding: Number.parseFloat(style.paddingTop), width: element.getBoundingClientRect().width }
  })
  expect(presentation.padding).toBeGreaterThanOrEqual(12)
  expect(presentation.width).toBeLessThanOrEqual(340)

  await page.goto('/components/date-picker')
  const basic = page.locator('#components-date-picker-panel-preview')
  const trigger = basic.getByRole('button', { name: 'Date', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Date', exact: true })
  const [triggerBox, dialogBox] = await Promise.all([trigger.boundingBox(), dialog.boundingBox()])
  expect(triggerBox).not.toBeNull()
  expect(dialogBox).not.toBeNull()
  expect(Math.abs(dialogBox!.x - triggerBox!.x)).toBeLessThanOrEqual(1)
  const blockGap = Math.min(
    Math.abs(dialogBox!.y - (triggerBox!.y + triggerBox!.height)),
    Math.abs(triggerBox!.y - (dialogBox!.y + dialogBox!.height)),
  )
  expect(blockGap).toBeLessThanOrEqual(12)
  await page.keyboard.press('Escape')

  const birthDate = page.locator('#components-date-picker-caption-panel-preview')
  await birthDate.getByRole('button', { name: 'Date of birth', exact: true }).click()
  const birthDateDialog = page.getByRole('dialog', { name: 'Date of birth', exact: true })
  const pickerYear = birthDateDialog.getByRole('combobox', { name: 'Year', exact: true })
  const pickerMonth = birthDateDialog.getByRole('combobox', { name: 'Month', exact: true })
  await pickerYear.selectOption('1920')
  await pickerMonth.selectOption('01')
  const firstPickerDay = birthDateDialog.getByRole('gridcell', { name: 'Thursday, January 15, 1920', exact: true })
  await firstPickerDay.press('PageUp')
  await expect(pickerYear).toHaveValue('1920')
  await expect(pickerMonth).toHaveValue('01')
  await expect(firstPickerDay).toBeFocused()
  await pickerYear.selectOption('2026')
  await pickerMonth.selectOption('12')
  const finalPickerDay = birthDateDialog.getByRole('gridcell', { name: 'Tuesday, December 15, 2026', exact: true })
  await finalPickerDay.press('PageDown')
  await expect(pickerYear).toHaveValue('2026')
  await expect(pickerMonth).toHaveValue('12')
  await expect(finalPickerDay).toBeFocused()
  await pickerYear.selectOption('1990')
  await pickerMonth.selectOption('02')
  await birthDateDialog.getByRole('gridcell', { name: 'Thursday, February 15, 1990', exact: true }).click()
  await expect(birthDate.getByRole('button', { name: 'Date of birth', exact: true })).toContainText('2/15/90')
  await page.setViewportSize({ width: 320, height: 1100 })
  await page.locator('html').evaluate(html => html.style.fontSize = '200%')
  await birthDate.getByRole('button', { name: 'Date of birth', exact: true }).click()
  await expect.poll(() => birthDateDialog.locator('[data-fve-month-calendar="selection"]').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await pickerYear.selectOption('2026')
  await pickerMonth.selectOption('09')
  await expect(birthDateDialog.getByRole('heading', { name: 'September 2026', exact: true })).toBeAttached()
})

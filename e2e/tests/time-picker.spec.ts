import { test, expect } from '../fixture'
import AxeBuilder from '@axe-core/playwright'

test('Application profile keeps time submission, validation, reset and server morph coherent @cross-browser', async ({ page }) => {
  await page.goto('/examples/application/profile/edit')
  const drawer = page.getByRole('dialog', { name: 'Edit profile', exact: true })
  const form = drawer.getByRole('form', { name: 'Edit profile', exact: true })
  const input = form.getByRole('combobox', { name: 'Daily summary time', exact: true })
  const submitted = () => form.evaluate(el => new FormData(el as HTMLFormElement).get('dailySummaryTime'))
  await expect(input).toHaveValue('9:00 AM')
  await form.locator('fve-time-picker').evaluate(el => {
    (window as any).__timeChanges = []
    el.addEventListener('change', event => (window as any).__timeChanges.push((event.target as HTMLInputElement).value))
  })
  await input.fill('2:30 PM')
  await input.press('Tab')
  expect(await submitted()).toBe('14:30')
  expect(await page.evaluate(() => (window as any).__timeChanges)).toEqual(['14:30'])
  await form.getByRole('button', { name: 'Choose daily summary time', exact: true }).click()
  await form.getByRole('option', { name: '10:15 AM', exact: true }).click()
  await expect(input).toHaveValue('10:15 AM')
  await input.press('ArrowDown')
  await input.press('ArrowDown')
  await input.press('Enter')
  await expect(input).toHaveValue('10:30 AM')
  expect(await submitted()).toBe('10:30')
  await input.fill('25:00')
  await input.press('Tab')
  await expect(input).toHaveValue('25:00')
  expect(await input.evaluate((el: HTMLInputElement) => el.checkValidity())).toBe(false)
  expect(await submitted()).toBe('')
  await drawer.getByRole('button', { name: 'Reset changes', exact: true }).click()
  await expect(input).toHaveValue('9:00 AM')

  await input.fill('11:15 AM')
  await form.getByLabel('Email', { exact: true }).fill('invalid-email')
  await form.evaluate((el: HTMLFormElement) => { el.noValidate = true })
  await drawer.getByRole('button', { name: 'Update', exact: true }).click()
  await expect(drawer.getByText('Enter a valid email address.', { exact: true })).toBeVisible()
  await expect(input).toHaveValue('11:15 AM')
  await input.fill('12:00 PM')
  await input.press('Tab')
  await drawer.getByRole('button', { name: 'Reset changes', exact: true }).click()
  await expect(input).toHaveValue('11:15 AM')
  expect(await submitted()).toBe('11:15')
  await form.getByLabel('Email', { exact: true }).fill('andrew@meiermade.com')
  await drawer.getByRole('button', { name: 'Update', exact: true }).click()
  await expect(page).toHaveURL(url => url.pathname === '/examples/application/profile')
  await expect(drawer).toHaveCount(0)
})

test('TimePicker bounds, keyboard dismissal and unavailable controls remain truthful @cross-browser', async ({ page }) => {
  await page.goto('/components/time-picker')
  const picker = page.locator('#office-time-field')
  const input = picker.getByRole('combobox', { name: 'Office visit', exact: true })
  await expect(input).toHaveValue('13:15')
  await input.press('ArrowDown')
  const current = picker.getByRole('option', { name: '13:15', exact: true })
  await expect(current).toHaveAttribute('tabindex', '0')
  await current.focus()
  await current.press('ArrowUp')
  await expect(picker.getByRole('option', { name: '13:00', exact: true })).toBeFocused()
  await picker.getByRole('option', { name: '13:00', exact: true }).press('Escape')
  await expect(input).toBeFocused()
  await input.press('ArrowDown')
  await input.press('End')
  await input.press('Enter')
  await expect(input).toHaveValue('18:15')
  await input.press('ArrowDown')
  await expect(picker.getByRole('option', { name: '08:00', exact: true })).toHaveCount(0)
  await expect(picker.getByRole('option', { name: '18:30', exact: true })).toHaveCount(0)
  await input.press('Escape')
  await expect(input).toBeFocused()
  await input.fill('13:17')
  await input.press('Tab')
  expect(await input.evaluate((el: HTMLInputElement) => el.checkValidity())).toBe(false)
  await expect(input).toHaveValue('13:17')
  await expect(page.locator('#disabled-time-field').getByRole('combobox', { name: 'Disabled', exact: true })).toBeDisabled()
  await expect(page.locator('#readonly-time-field').getByRole('combobox', { name: 'Read-only', exact: true })).not.toBeEditable()
  await expect(page.locator('#readonly-time-field').getByRole('button', { name: 'Choose read-only', exact: true })).toBeDisabled()
})

test('TimePicker popup stays usable at narrow enlarged text @cross-browser', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 1100 })
  await page.goto('/components/time-picker')
  await page.evaluate(() => { document.documentElement.style.fontSize = '200%'; document.documentElement.classList.add('dark'); document.documentElement.dataset.theme = 'dark' })
  const picker = page.locator('#default-time-field')
  const input = picker.getByRole('combobox', { name: 'Time', exact: true })
  await picker.getByRole('button', { name: 'Choose time', exact: true }).click()
  const panel = picker.getByRole('dialog', { name: 'Time options', exact: true })
  await expect(panel).toBeVisible()
  expect((await new AxeBuilder({ page }).include('#default-time-field').analyze()).violations).toEqual([])
  const box = (await panel.boundingBox())!
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(321)
  const control = (await input.boundingBox())!
  expect(box.y + box.height <= control.y || box.y >= control.y + control.height).toBe(true)
  await picker.getByRole('option', { name: '10:30 AM', exact: true }).click()
  await expect(input).toHaveValue('10:30 AM')
})

test.describe('TimePicker native fallback', () => {
  test.use({ javaScriptEnabled: false })
  test('Application profile submits a canonical time without JavaScript', async ({ page }) => {
    await page.goto('/examples/application/profile/edit')
    const form = page.getByRole('form', { name: 'Edit profile', exact: true })
    await form.getByRole('textbox', { name: 'Daily summary time', exact: true }).fill('14:30')
    const submitted = page.waitForRequest(request => request.method() === 'POST' && new URL(request.url()).pathname === '/examples/application/profile/edit')
    await page.getByRole('button', { name: 'Update', exact: true }).click()
    expect(new URLSearchParams((await submitted).postData()!).get('dailySummaryTime')).toBe('14:30')
    await expect(page).toHaveURL(url => url.pathname === '/examples/application/profile')
  })
})

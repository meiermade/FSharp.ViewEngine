test('time range keeps native fields, keyboard edits, unavailable feedback and reset coherent @cross-browser', async ({ page }) => {
  await page.goto('/components/day-calendar')
  const form = page.getByRole('form', { name: 'Review a consultation time' })
  const range = form.locator('fve-calendar-range')
  const start = form.getByRole('combobox', { name: 'Start time', exact: true })
  const duration = form.getByRole('combobox', { name: 'Duration', exact: true })
  const move = range.getByRole('button', { name: 'Move selected time range', exact: true })
  await move.press('ArrowDown')
  await expect(start).toHaveValue('09:30')
  await move.press('Shift+ArrowDown')
  await expect(duration).toHaveText('90 minutes')
  await duration.click()
  await form.getByRole('option', { name: '30 minutes', exact: true }).click()
  await expect(duration).toHaveText('30 minutes')
  await expect(range.locator('[data-range-label]')).toHaveText('09:30–10:00')
  expect(await form.evaluate(el => new FormData(el as HTMLFormElement).get('selection.minutes'))).toBe('30')
  await duration.click()
  await form.getByRole('option', { name: '90 minutes', exact: true }).click()
  await expect(duration).toHaveText('90 minutes')
  await start.fill('10:00')
  await start.press('Tab')
  await expect(range.locator('[data-range-status]')).toHaveText(/unavailable/)
  expect(await start.evaluate((el: HTMLInputElement) => el.checkValidity())).toBe(false)
  await expect(start).toHaveValue('10:00')
  await form.getByRole('button', { name: 'Reset selection' }).click()
  await expect(start).toHaveValue('09:00')
  await expect(duration).toHaveText('60 minutes')
  expect(await start.evaluate((el: HTMLInputElement) => el.checkValidity())).toBe(true)
  await move.press('ArrowDown')
  await duration.click()
  await form.getByRole('option', { name: '90 minutes', exact: true }).click()
  await form.getByRole('button', { name: 'Review time', exact: true }).click()
  await expect(page).toHaveURL(url => url.searchParams.get('selection.start') === '09:30' && url.searchParams.get('selection.minutes') === '90')
  await expect(page.locator('#calendar-day-result')).toContainText('Provisional selection:')
  await expect(start).toHaveValue('09:30')
  await expect(range.locator('[data-range-status]')).toHaveText('Selected time is available.')
  await form.getByRole('button', { name: 'Reset selection' }).click()
  await expect(start).toHaveValue('09:30')
  await expect(duration).toHaveText('90 minutes')
  await form.getByRole('button', { name: 'Choose start time', exact: true }).click()
  await expect(form.getByRole('option', { name: '09:30', exact: true })).toHaveAttribute('aria-selected', 'true')
  await expect(form.getByRole('option', { name: '21:00', exact: true })).toHaveCount(0)
  await form.getByRole('option', { name: '13:00', exact: true }).click()
  await expect(range.locator('[data-range-label]')).toHaveText('13:00–14:30')
  expect(await form.evaluate(el => new FormData(el as HTMLFormElement).get('selection.start'))).toBe('13:00')
  await move.press('ArrowUp')
  await expect(start).toHaveValue('12:30')
  await form.getByRole('button', { name: 'Choose start time', exact: true }).click()
  await expect(form.getByRole('option', { name: '12:30', exact: true })).toHaveAttribute('aria-selected', 'true')
  await start.press('Escape')
  const timeHeight = await range.locator('.fve-input-group').evaluate(el => el.getBoundingClientRect().height)
  expect(timeHeight).toBe(await duration.evaluate(el => el.getBoundingClientRect().height))
  expect((await new AxeBuilder({ page }).include('#calendar-time-range').analyze()).violations).toEqual([])
})

test('time range pointer moves commit once and Escape cancels an in-flight gesture @cross-browser', async ({ page }) => {
  await page.goto('/components/day-calendar')
  const range = page.locator('#calendar-time-range-range')
  const start = range.getByRole('combobox', { name: 'Start time', exact: true })
  await range.evaluate(el => { (window as any).__rangeChanges = []; el.addEventListener('fve-calendar-range-change', (event: any) => (window as any).__rangeChanges.push(event.detail)) })
  const body = range.locator('.fve-calendar-body')
  await body.evaluate(el => { el.scrollTop = 160 })
  const move = range.getByRole('button', { name: 'Move selected time range', exact: true })
  await move.scrollIntoViewIfNeeded()
  let box = (await move.boundingBox())!
  const step = await range.locator('.fve-calendar-events').evaluate(el => el.getBoundingClientRect().height / 16 / 2)
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + step, { steps: 4 })
  await page.mouse.up()
  await expect(start).toHaveValue('09:30')
  expect(await page.evaluate(() => (window as any).__rangeChanges.length)).toBe(1)
  box = (await move.boundingBox())!
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
  await page.mouse.down()
  await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2 + step, { steps: 4 })
  await expect(start).toHaveValue('10:00')
  await page.keyboard.press('Escape')
  await page.mouse.up()
  await expect(start).toHaveValue('09:30')
  expect(await page.evaluate(() => (window as any).__rangeChanges.length)).toBe(1)
  for (const [part, time, minutes] of [['end', '09:30', '90'], ['start', '10:00', '60']]) {
    const grip = range.locator(`[data-range-part=${part}]`)
    await grip.scrollIntoViewIfNeeded()
    const bounds = (await grip.boundingBox())!
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2)
    await page.mouse.down()
    await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2 + step, { steps: 4 })
    await page.mouse.up()
    await expect(start).toHaveValue(time)
    await expect(range.getByRole('combobox', { name: 'Duration', exact: true })).toHaveText(`${minutes} minutes`)
    expect(await range.evaluate(el => new FormData(el.closest('form')!).get('selection.minutes'))).toBe(minutes)
  }
  expect(await page.evaluate(() => (window as any).__rangeChanges.length)).toBe(3)
})

test('blank-slot mouse clicks use the highlighted start, not the nearest boundary @cross-browser', async ({ page }) => {
  await page.goto('/components/day-calendar?selection.start=09%3A30&selection.minutes=30')
  const form = page.getByRole('form', { name: 'Review a consultation time' })
  const range = form.locator('fve-calendar-range')
  for (const time of ['09:00', '10:00']) {
    for (const fraction of [.25, .5, .75]) {
      await form.getByRole('button', { name: 'Reset selection', exact: true }).click()
      await expect(range.getByRole('combobox', { name: 'Start time', exact: true })).toHaveValue('09:30')
      const slot = range.getByRole('button', { name: `Choose ${time}`, exact: true })
      await slot.scrollIntoViewIfNeeded()
      const box = (await slot.boundingBox())!
      await page.mouse.click(box.x + box.width / 2, box.y + box.height * fraction)
      await expect(range.getByRole('combobox', { name: 'Start time', exact: true })).toHaveValue(time)
      await expect(range.getByRole('combobox', { name: 'Duration', exact: true })).toHaveText('30 minutes')
      await expect(range.locator('[data-range-label]')).toHaveText(`${time}–${time.slice(0, 2)}:30`)
    }
  }
})


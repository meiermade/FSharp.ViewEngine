test('calendar date and view controls preserve the draft through real server-rendered state @cross-browser', async ({ page }) => {
  await page.goto('/components/day-calendar?selection.start=13%3A00&selection.minutes=60')
  const calendar = page.locator('#calendar-day-controls')
  const dateControl = calendar.getByRole('form', { name: 'Calendar date', exact: true })
  await expect(dateControl.getByRole('button', { name: 'Show date', exact: true })).toHaveCount(0)
  const initialUrl = page.url()
  await dateControl.getByLabel('Calendar date', { exact: true }).fill('')
  await expect(page).toHaveURL(initialUrl)
  await dateControl.getByLabel('Calendar date', { exact: true }).fill('2026-09-13')
  await expect(page).toHaveURL(initialUrl)
  await dateControl.getByLabel('Calendar date', { exact: true }).fill('2026-09-18')
  await expect(page).toHaveURL(url => url.searchParams.get('calendarDate') === '2026-09-18' && url.searchParams.get('selection.start') === '13:00')
  await expect(page.locator('#calendar-time-range-range').getByRole('combobox', { name: 'Start time', exact: true })).toHaveValue('13:00')
  await calendar.getByRole('navigation', { name: 'Calendar view' }).getByRole('link', { name: 'Week', exact: true }).click()
  await expect(page).toHaveURL(url => url.pathname === '/components/week-calendar' && url.searchParams.get('selection.start') === '13:00')
  const week = page.locator('#calendar-week-controls')
  await expect(week.getByRole('navigation', { name: 'Calendar view' }).getByRole('link', { name: 'Week', exact: true })).toHaveAttribute('aria-current', 'page')
  const weekDate = week.getByRole('form', { name: 'Calendar date', exact: true })
  await weekDate.getByLabel('Calendar date', { exact: true }).fill('2026-09-19')
  await expect(page).toHaveURL(url => url.searchParams.get('calendarDate') === '2026-09-19' && url.searchParams.get('selection.start') === '13:00' && url.searchParams.get('selection.minutes') === '60')
  await expect(page.locator('#calendar-week-result')).toContainText('Sep 19, 13:00')
  expect((await new AxeBuilder({ page }).include('#calendar-week-controls').analyze()).violations).toEqual([])
})

test('overlapping event cards raise without shifting and open reusable details @cross-browser', async ({ page }) => {
  await page.goto('/components/day-calendar')
  const calendar = page.locator('#calendar-day-events')
  const first = calendar.getByRole('button', { name: /Coastal trail lesson/ })
  const geometry = () => calendar.locator('[data-timed=true]').evaluateAll(nodes => nodes.map(el => {
    const box = el as HTMLElement
    return [box.offsetLeft, box.offsetTop, box.offsetWidth, box.offsetHeight]
  }))
  await first.scrollIntoViewIfNeeded()
  const before = await geometry()
  await first.focus()
  expect(await calendar.evaluate(el => {
    const first = el.querySelector('[data-event="lesson-201"]')!.getBoundingClientRect()
    const second = el.querySelector('[data-event="camp-017"]')!.getBoundingClientRect()
    return document.elementFromPoint(second.left + 10, Math.max(first.top, second.top) + 10)?.closest('[data-event]')?.getAttribute('data-event')
  })).toBe('lesson-201')
  await first.press('Enter')
  const panel = calendar.getByRole('dialog', { name: 'Coastal trail lesson', exact: true })
  await expect(panel).toBeVisible()
  await expect(panel).toContainText('Maya and Sam')
  await expect(panel.getByRole('link', { name: 'View event', exact: true })).toHaveAttribute('href', /item=lesson-201/)
  await expect(panel.getByRole('button', { name: 'Close event details' })).toBeFocused()
  expect(await geometry()).toEqual(before)
  expect((await new AxeBuilder({ page }).include('#calendar-day-events').analyze()).violations).toEqual([])
  await page.keyboard.press('Escape')
  await expect(panel).not.toBeVisible()
  await expect(first).toBeFocused()
  const second = calendar.getByRole('button', { name: /Beginner riding camp/ })
  await second.click()
  await expect(calendar.getByRole('dialog', { name: 'Beginner riding camp', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(second).toBeFocused()
  const range = page.locator('#calendar-time-range-range')
  await range.getByRole('button', { name: /Your consultation/ }).click()
  const occupied = range.getByRole('dialog', { name: 'Your consultation', exact: true })
  await expect(occupied).toBeVisible()
  expect((await new AxeBuilder({ page }).include('#calendar-time-range').analyze()).violations).toEqual([])
  await occupied.getByRole('button', { name: 'Close event details' }).click()
  await expect(occupied).not.toBeVisible()
  await expect(range.getByRole('combobox', { name: 'Start time', exact: true })).toHaveValue('09:00')
  const shortEvent = range.getByRole('button', { name: /Unavailable · Team briefing/ })
  await shortEvent.scrollIntoViewIfNeeded()
  const metrics = await shortEvent.evaluate(el => {
    const title = el.querySelector('strong')!
    return { height: el.getBoundingClientRect().height, titleHeight: title.getBoundingClientRect().height, lineHeight: parseFloat(getComputedStyle(title).lineHeight), client: el.clientHeight, scroll: el.scrollHeight }
  })
  expect(metrics.titleHeight).toBeGreaterThanOrEqual(metrics.lineHeight)
  expect(metrics.scroll).toBeGreaterThan(metrics.client)
  await shortEvent.hover()
  await page.mouse.wheel(0, 80)
  await expect.poll(() => shortEvent.evaluate(el => el.scrollTop)).toBeGreaterThan(0)
  expect((await shortEvent.boundingBox())!.height).toBe(metrics.height)
  await expect(range.getByRole('dialog')).toHaveCount(0)
})


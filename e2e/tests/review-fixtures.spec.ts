import { test, expect } from '../fixture'

for (const kind of ['Browser', 'Phone']) {
  test(`${kind} review fixture expands and restores through real links @cross-browser`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.goto(`/components/${kind.toLowerCase()}`)
    await page.evaluate(() => { document.documentElement.dataset.reviewSession = 'retained' })
    const expand = page.getByRole('link', { name: `Expand ${kind} fixture`, exact: true })
    await expand.focus()
    await page.keyboard.press('Enter')
    await expect(page).toHaveURL(/expanded=1/)
    await expect(page.locator('html')).toHaveAttribute('data-review-session', 'retained')
    const frame = page.locator(kind === 'Browser' ? '[data-fve-browser-expanded=true]' : '[data-fve-phone-expanded=true]')
    await expect(frame).toBeVisible()
    if (kind === 'Browser') await expect(frame.locator('[data-fve-browser-address]')).toHaveText('/components/browser')
    else {
      await expect(frame.locator('[data-fve-browser-address]')).toHaveCount(0)
      expect(await frame.locator('[data-fve-phone-toolbar]').evaluate(el => !!el.closest('[data-fve-phone-screen]'))).toBe(false)
    }
    await frame.getByRole('button', { name: 'Choose fixture theme', exact: true }).click()
    await page.getByRole('menuitemradio', { name: 'Dark', exact: true }).click()
    await expect(page.locator('html')).toHaveClass(/dark/)
    await page.reload()
    await page.keyboard.press('Escape')
    await expect(page).toHaveURL(url => !url.searchParams.has('expanded'))
    await expect(expand).toBeFocused()
    await expect(expand).toBeInViewport()
    await page.goBack()
    await expect(frame).toBeVisible()
    await page.goForward()
    await expect(expand).toBeVisible()
    expect(errors).toEqual([])
  })
}

test('fixture state and authored journey remain separate, with scroll and focus restored @cross-browser', async ({ page }) => {
  await page.goto('/examples/specification/accounts/view-accounts')
  const frame = page.locator('[data-review-fixture]')
  const state = page.getByRole('button', { name: /^Review state:/ })
  await state.click()
  await page.getByRole('menuitem', { name: 'Assets', exact: true }).click()
  await expect(page).toHaveURL(/specState=assets/)
  const next = frame.getByRole('link', { name: 'Next: View account', exact: true })
  await expect(next).toHaveAttribute('href', /accounts\/view-account/)
  const expand = frame.getByRole('link', { name: 'Expand View accounts · Assets', exact: true })
  await expand.scrollIntoViewIfNeeded()
  const scroll = await page.locator('[data-fve-page-scroll]').first().evaluate(el => el.scrollTop)
  await expand.click()
  await expect(page.locator('[data-fve-browser-expanded=true]')).toBeVisible()
  await state.click()
  await page.getByRole('menuitem', { name: 'Hierarchy', exact: true }).click()
  await expect(page).toHaveURL(/specState=default.*appMode=1/)
  await expect(next).toHaveAttribute('href', /accounts\/view-account/)
  await frame.getByRole('link', { name: 'Restore View accounts · Hierarchy', exact: true }).click()
  await expect(frame.getByRole('link', { name: 'Expand View accounts · Hierarchy', exact: true })).toBeFocused()
  await expect.poll(() => page.locator('[data-fve-page-scroll]').first().evaluate(el => el.scrollTop)).toBe(scroll)
  await page.goto('/examples/specification/profile?appMode=1')
  await expect(page.getByRole('link', { name: /^Next:/ })).toHaveCount(0)
  await expect(page.getByLabel('No next journey step', { exact: true })).toBeVisible()
})


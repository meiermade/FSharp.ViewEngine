import { test, expect } from '../fixture'

test('top-level Guides keep workflows separate and support enhanced navigation, history and search @cross-browser', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/guides/scripts')
  await page.evaluate(() => { (window as any).guideDocument = 'retained' })
  const navigation = page.locator('#side-nav')
  for (const [name, path] of [
    ['Standalone F# scripts', '/guides/scripts'], ['Giraffe integration', '/guides/giraffe'],
    ['Using signals', '/guides/using-signals'], ['Theming', '/guides/theming'], ['Presentations', '/guides/presentations']
  ]) await expect(navigation.getByRole('link', { name, exact: true })).toHaveAttribute('href', path)
  await expect(page.getByRole('heading', { name: 'Standalone F# scripts', exact: true, level: 1 })).toBeVisible()
  await expect(page.locator('main')).toContainText('fveCard')
  await expect(page.locator('main')).not.toContainText('fvePresentation {')
  await navigation.getByRole('link', { name: 'Giraffe integration', exact: true }).click()
  await expect(page).toHaveURL('/guides/giraffe')
  await expect(page.getByRole('heading', { name: 'Giraffe integration', exact: true, level: 1 })).toBeVisible()
  await navigation.getByRole('link', { name: 'Theming', exact: true }).click()
  await expect(page).toHaveURL('/guides/theming')
  await expect(page.locator('main details:not([data-docs-mobile-toc])')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Theme API', exact: true })).toBeAttached()
  await navigation.getByRole('link', { name: 'Presentations', exact: true }).click()
  await expect(page).toHaveURL('/guides/presentations')
  await expect(page.getByRole('heading', { name: 'Build a presentation', exact: true, level: 1 })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Print or save as PDF', exact: true })).toBeAttached()
  await expect(page.locator('main details:not([data-docs-mobile-toc])')).toHaveCount(0)
  await page.goBack()
  await expect(page).toHaveURL('/guides/theming')
  await expect(page.getByRole('heading', { name: 'Theming', exact: true, level: 1 })).toBeVisible()
  await page.goForward()
  await expect(page).toHaveURL('/guides/presentations')
  await expect(page.getByRole('heading', { name: 'Build a presentation', exact: true, level: 1 })).toBeVisible()
  await page.getByRole('button', { name: 'Search documentation', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Search documentation', exact: true })
  await dialog.getByRole('combobox').fill('Standalone F# scripts')
  const scripts = dialog.locator('[data-fve-command-item][href="/guides/scripts"]')
  await expect(scripts).toBeVisible()
  await scripts.focus()
  await page.keyboard.press('Enter')
  await expect(page).toHaveURL('/guides/scripts')
  expect(await page.evaluate(() => (window as any).guideDocument)).toBe('retained')
  expect(errors).toEqual([])
})

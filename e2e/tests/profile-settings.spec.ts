test('wide application headers, details and tables share the available content width', async ({ page }) => {
  await page.setViewportSize({ width: 2000, height: 1000 })
  for (const path of ['profile', 'settings/general', 'settings/users']) {
    await page.goto(`/examples/application/${path}`)
    const heading = (await page.getByRole('heading', { level: 1 }).boundingBox())!
    const content = path.endsWith('users') ? page.getByRole('table') : page.getByRole('region', { name: 'Details', exact: true })
    const bounds = (await content.boundingBox())!
    expect(bounds.x).toBeCloseTo(heading.x, 1)
    expect(bounds.x + bounds.width).toBeCloseTo(1968, 1)
    expect(bounds.x).toBeCloseTo(272, 1)
  }
})

// Form submission remains PR/local/staging regression coverage, not production smoke.
test('stateless financial form accepts the public HTTPS origin without retaining values', async ({ page }) => {
  await page.goto('/examples/application/settings/general')
  await page.getByRole('link', { name: 'Edit', exact: true }).click()
  const form = page.getByRole('dialog', { name: 'Edit organization', exact: true })
  const name = form.getByRole('textbox', { name: 'Name', exact: true })
  const seededName = await name.inputValue()
  const update = form.getByRole('button', { name: 'Update', exact: true })
  const idle = (await update.boundingBox())!
  const action = new URL(await update.evaluate(el => (el as HTMLButtonElement).form!.action))
  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route(url => url.origin === action.origin && url.pathname === action.pathname, async route => {
    await held
    await route.continue()
  }, { times: 1 })
  await name.fill('Production smoke workspace')
  try {
    await update.click()
    await expect(update).toHaveAttribute('aria-busy', 'true')
    await expect(update).toHaveAccessibleName('Update')
    await expect(update.locator('[aria-hidden="true"]')).toBeVisible()
    const busy = (await update.boundingBox())!
    expect([busy.width, busy.height]).toEqual([idle.width, idle.height])
  } finally {
    release()
  }
  await expect(form).toHaveCount(0)
  await expect(page).toHaveURL(url => url.pathname === '/examples/application/settings/general')
  expect([...new URL(page.url()).searchParams.values()].join(' ')).not.toContain('Production smoke workspace')
  await page.getByRole('link', { name: 'Edit', exact: true }).click()
  await expect(name).toHaveValue(seededName)
  await form.getByRole('link', { name: 'Cancel', exact: true }).click()
  await expect(form).toHaveCount(0)
})

test('workspace selector releases modal interaction after environment and organization changes @cross-browser', async ({ page }) => {
  await page.goto('/examples/application')
  await page.evaluate(() => document.documentElement.dataset.workspaceSession = 'same-document')
  for (const environment of ['Staging', 'Production']) {
    await page.getByRole('button', { name: 'Open workspace menu: Alex', exact: true }).click()
    const environmentItem = page.getByRole('menuitem', { name: /^Environment/ })
    await expect(environmentItem.locator('svg[aria-hidden=true]')).toHaveCount(2)
    await environmentItem.click()
    await page.getByRole('dialog', { name: 'Change environment', exact: true }).getByRole('link', { name: new RegExp(`^${environment}`) }).click()
    await expect(page).toHaveURL(url => url.searchParams.get('environment') === environment.toLowerCase())
    await expect(page.locator('dialog:modal')).toHaveCount(0)
  }
  await page.getByRole('button', { name: 'Open workspace menu: Alex', exact: true }).click()
  const organizationItem = page.getByRole('menuitem', { name: /^Organization/ })
  await expect(organizationItem.locator('svg[aria-hidden=true]')).toHaveCount(2)
  await organizationItem.click()
  await page.getByRole('dialog', { name: 'Change organization', exact: true }).getByRole('link', { name: /^Client Organization/ }).click()
  await expect(page).toHaveURL(url => url.searchParams.get('organization') === 'client-organization')
  await expect(page.locator('dialog:modal')).toHaveCount(0)
  await page.locator('#template-desktop-navigation').getByRole('link', { name: 'Accounts', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Accounts', level: 1, exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-workspace-session', 'same-document')
})


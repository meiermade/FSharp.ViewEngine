import { test, expect, type Locator } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

const entries = (form: Locator) => form.evaluate(element => [...new FormData(element as HTMLFormElement).entries()])

test('Switch keeps native form/reset state and works after a server patch @cross-browser', async ({ page }) => {
  await page.goto('/components/switch')
  const region = page.locator('#components-switch-form-region')
  const form = region.locator('form')
  const control = region.getByRole('switch', { name: 'Notifications', exact: true })
  await expect(control).toBeChecked()
  await control.press('Space')
  expect(await entries(form)).toEqual([])
  await form.evaluate(form => (form as HTMLFormElement).reset())
  await expect(control).toBeChecked()
  await control.press('Space')
  await region.getByRole('button', { name: 'Save notifications' }).click()
  await expect(region.getByRole('status')).toHaveText('Notifications disabled.')
  await control.press('Space')
  await region.getByRole('button', { name: 'Save notifications' }).click()
  await expect(region.getByRole('status')).toHaveText('Notifications enabled.')
  expect(await entries(form)).toEqual([['notifications', 'true']])
  const pending = page.getByRole('switch', { name: 'Saving notifications', exact: true })
  await pending.press('Space')
  await expect(pending).toBeChecked()
  expect(await pending.evaluate(el => (el as HTMLInputElement).disabled)).toBe(false)
  await expect(page.getByRole('switch', { name: 'Notifications unavailable', exact: true })).toBeDisabled()
  expect((await new AxeBuilder({ page }).include('#components-switch-panel-preview').analyze()).violations).toEqual([])
})

test('FileSelection always provides contextual clearing for native selections @cross-browser', async ({ page }) => {
  await page.goto('/components/file-selection')
  const basic = page.locator('#components-file-selection-default-panel-preview')
  await expect(basic.locator('input[type=file]')).toHaveCount(1)
  await expect(basic.locator('ul')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Pending', exact: true })).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Clearable', exact: true })).toHaveCount(0)
  const single = basic
  const file = single.getByLabel('File', { exact: true })
  const clear = single.getByRole('button', { name: /^Clear File selection/, includeHidden: true })
  await expect(clear).toBeHidden()
  const selected = { name: 'invoice.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7') }
  await file.setInputFiles(selected)
  await expect(clear).toBeVisible()
  await expect(clear).toHaveText('Clear')
  await expect(clear).toHaveAccessibleName('Clear File selection: invoice.pdf')
  await expect(single.locator('ul')).toHaveCount(0)
  const navigationRoot = page.locator('[data-fve-navigation-root]')
  const previousDocument = await navigationRoot.getAttribute('data-navigation-document')
  await page.locator('#nav-components-file-selection').click()
  await expect.poll(() => navigationRoot.getAttribute('data-navigation-document')).not.toBe(previousDocument)
  await expect(clear).toBeVisible()
  await expect(clear).toHaveAccessibleName('Clear File selection: invoice.pdf')
  expect(await file.evaluate((input: HTMLInputElement) => input.files![0].name)).toBe('invoice.pdf')
  for (const property of ['disabled', 'readOnly'] as const) {
    await file.evaluate((input: HTMLInputElement, property) => { input[property] = true }, property)
    await expect(clear).toBeHidden()
    await clear.evaluate((button: HTMLButtonElement) => button.click())
    expect(await file.evaluate((input: HTMLInputElement) => input.files![0].name)).toBe('invoice.pdf')
    await file.evaluate((input: HTMLInputElement, property) => { input[property] = false }, property)
    await expect(clear).toBeVisible()
  }
  await file.evaluate(input => {
    input.addEventListener('input', () => input.setAttribute('data-input-event', 'true'))
    input.addEventListener('change', () => input.setAttribute('data-change-event', 'true'))
  })
  await clear.click()
  await expect(file).toHaveValue('')
  await expect(file).toBeFocused()
  await expect(file).toHaveAttribute('data-input-event', 'true')
  await expect(file).toHaveAttribute('data-change-event', 'true')
  await expect(clear).toBeHidden()
  const explicitlyLabelled = single.locator('input[type=file]')
  await explicitlyLabelled.evaluate(input => input.setAttribute('aria-label', 'File picker'))
  await explicitlyLabelled.setInputFiles(selected)
  const labelledClear = single.getByRole('button', { name: 'Clear File picker selection: invoice.pdf', exact: true })
  await expect(labelledClear).toBeVisible()
  await labelledClear.press('Enter')
  await expect(explicitlyLabelled).toHaveValue('')

  const multiple = page.locator('#components-file-selection-panel-preview')
  const input = multiple.getByLabel('Files', { exact: true })
  const clearAll = multiple.getByRole('button', { name: /^Clear Files selection/, includeHidden: true })
  await input.evaluate(input => {
    const wrapper = input.parentElement!
    const form = document.createElement('form')
    wrapper.before(form)
    form.append(wrapper)
  })
  const files = [{ name: 'one.csv', mimeType: 'text/csv', buffer: Buffer.from('one') }, { name: 'two.csv', mimeType: 'text/csv', buffer: Buffer.from('two') }]
  await input.setInputFiles(files)
  await expect(clearAll).toBeVisible()
  expect(await input.evaluate((input: HTMLInputElement) => new FormData(input.form!).getAll('selectedFiles').map(file => (file as File).name))).toEqual(['one.csv', 'two.csv'])
  await input.evaluate((input: HTMLInputElement) => input.form!.reset())
  await expect(input).toHaveValue('')
  await expect(clearAll).toBeHidden()
  await input.setInputFiles(files)
  await clearAll.press('Space')
  await expect(input).toHaveValue('')
  await expect(input).toBeFocused()
  await expect(clearAll).toBeHidden()
  await expect(page.getByLabel('Files unavailable', { exact: true })).toBeDisabled()
  expect((await new AxeBuilder({ page }).include('[data-docs-layout="gallery"]').analyze()).violations).toEqual([])
})

test('file validation reacts to selection and native submission, not picker blur @cross-browser', async ({ page }) => {
  await page.goto('/components/file-selection')
  const region = page.locator('#components-file-selection-validation-panel-preview')
  const file = region.getByLabel('Document (required)', { exact: true })
  const error = region.getByRole('alert')
  await file.evaluate(input => {
    const form = document.createElement('form')
    input.before(form)
    form.append(input)
  })
  await expect(error).toBeHidden()
  await expect(region.locator('ul')).toHaveCount(0)
  const clear = region.getByRole('button', { name: /^Clear Document \(required\) selection/, includeHidden: true })
  await expect(clear).toBeHidden()
  await file.focus(); await file.blur()
  await expect(error).toBeHidden()
  await file.evaluate(input => input.dispatchEvent(new Event('cancel', { bubbles: true })))
  await expect(error).toBeHidden()
  await file.evaluate((input: HTMLInputElement) => input.reportValidity())
  await expect(error).toHaveText('Select a PDF document.')
  await file.setInputFiles({ name: 'image.png', mimeType: 'image/png', buffer: Buffer.from('image') })
  await expect(error).toHaveText('The selected file must be a PDF.')
  expect(await file.evaluate((input: HTMLInputElement) => input.validity.customError)).toBe(true)
  await file.setInputFiles({ name: 'document.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7') })
  await expect(error).toBeHidden()
  await expect(file).not.toHaveAttribute('aria-invalid')
  await expect(file).toHaveAttribute('aria-describedby', 'required-file-help')
  expect(await file.evaluate((input: HTMLInputElement) => input.validity.valid)).toBe(true)
  await expect(clear).toHaveAccessibleName('Clear Document (required) selection: document.pdf')
  await clear.click()
  await expect(file).toHaveValue('')
  await expect(file).toBeFocused()
  await expect(clear).toBeHidden()
  await expect(error).toHaveText('Select a PDF document.')
  await file.setInputFiles({ name: 'document.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7') })
  await expect(error).toBeHidden()
  await expect(clear).toBeVisible()
  await file.evaluate((input: HTMLInputElement) => input.form!.reset())
  await expect(error).toBeHidden()
  await expect(file).not.toHaveAttribute('aria-invalid')
  await expect(clear).toBeHidden()
})

test('RadioGroup uses native arrows, required validation and successful read-only values @cross-browser', async ({ page }) => {
  await page.goto('/components/radio-group')
  const region = page.locator('#components-radio-form-region')
  const form = region.locator('form')
  await region.getByRole('button', { name: 'Validate choice' }).click()
  await expect(region.getByRole('alert')).toHaveText('Choose an available update mode.')
  const automatic = region.getByRole('radio', { name: 'Automatic', exact: true })
  const manual = region.getByRole('radio', { name: 'Manual review', exact: true })
  await automatic.check()
  await automatic.press('ArrowDown')
  await expect(manual).toBeChecked()
  await expect(region.getByRole('radio', { name: 'Scheduled' })).toBeDisabled()
  await region.getByRole('button', { name: 'Validate choice' }).click()
  await expect(region.getByRole('status')).toHaveText('Accepted update mode: Manual review.')
  await manual.press('ArrowUp')
  await expect(automatic).toBeChecked()
  expect(await entries(form)).toEqual([['updateMode', 'automatic']])
  const pending = page.getByRole('radiogroup', { name: 'Saving update mode' })
  const locked = pending.getByRole('radio', { name: 'Automatic', exact: true })
  await locked.press('ArrowDown')
  await pending.getByRole('radio', { name: 'Manual review', exact: true }).click({ force: true })
  await expect(locked).toBeChecked()
  expect(await locked.evaluate(el => (el as HTMLInputElement).disabled)).toBe(false)
  expect((await new AxeBuilder({ page }).include('#components-radio-group-panel-preview').analyze()).violations).toEqual([])
})

test('Toggle groups preserve cardinality, selection order, keyboard focus, reset and server patches @cross-browser', async ({ page }) => {
  await page.goto('/components/toggle-button')
  const button = page.getByRole('button', { name: 'Compact rows', exact: true })
  await button.press('Space')
  await expect(button).toHaveAttribute('aria-pressed', 'true')
  await button.press('Enter')
  await expect(button).toHaveAttribute('aria-pressed', 'false')
  await page.goto('/components/toggle-group')
  const single = page.locator('#components-alignment-group')
  await single.getByRole('button', { name: 'Center', exact: true }).click()
  await expect(single.getByRole('button', { pressed: true })).toHaveText('Center')
  const region = page.locator('#components-toggle-form-region')
  const form = region.locator('form')
  const bold = region.getByRole('button', { name: 'Bold', exact: true })
  const italic = region.getByRole('button', { name: 'Italic', exact: true })
  await bold.focus()
  await bold.press('ArrowRight')
  await expect(italic).toBeFocused()
  await italic.press('Space')
  await expect.poll(() => entries(form)).toEqual([['format', 'bold'], ['format', 'italic']])
  await region.getByRole('button', { name: 'Save formatting' }).click()
  await expect(region.getByRole('status')).toHaveText('Saved formatting: bold, italic.')
  await bold.click()
  await expect.poll(() => entries(form)).toEqual([['format', 'italic']])
  await form.evaluate(form => (form as HTMLFormElement).reset())
  await expect.poll(() => entries(form)).toEqual([['format', 'bold'], ['format', 'italic']])
  await bold.click()
  await italic.click()
  await region.getByRole('button', { name: 'Save formatting' }).click()
  await expect(region.getByRole('alert')).toHaveText('Choose at least one available format.')
  await italic.click()
  await region.getByRole('button', { name: 'Save formatting' }).click()
  await expect(region.getByRole('status')).toHaveText('Saved formatting: italic.')
  expect((await new AxeBuilder({ page }).include('#components-toggle-group-default-panel-preview').analyze()).violations).toEqual([])
})

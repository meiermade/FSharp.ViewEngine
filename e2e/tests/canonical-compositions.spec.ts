test('native filter checkboxes apply multiple choices and clear without JavaScript', async ({ browser }) => {
  const context = await browser.newContext({ javaScriptEnabled: false })
  const page = await context.newPage()
  try {
    await page.goto('/examples/application/accounts?filters=accountType')
    const filter = page.getByRole('group', { name: 'Type', exact: true })
    await filter.getByRole('checkbox', { name: 'Asset', exact: true }).check()
    await filter.getByRole('checkbox', { name: 'Liability', exact: true }).check()
    await page.getByRole('button', { name: 'Apply Type filter', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Operating checking', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Business credit card', exact: true })).toBeVisible()
    await expect(page.getByRole('link', { name: 'Unassigned expense', exact: true })).toHaveCount(0)
    await filter.getByRole('checkbox', { name: 'Asset', exact: true }).uncheck()
    await filter.getByRole('checkbox', { name: 'Liability', exact: true }).uncheck()
    await page.getByRole('button', { name: 'Apply Type filter', exact: true }).click()
    await expect(page.getByRole('link', { name: 'Unassigned expense', exact: true })).toBeVisible()
  } finally { await context.close() }
})

test('account drawer preserves context and leaves edited forms without prompts @cross-browser', async ({ page }) => {
  const prompts: string[] = []
  page.on('dialog', async prompt => { prompts.push(prompt.message()); await prompt.accept() })
  await page.goto('/examples/application/accounts?search=checking&sort=balance')
  await page.getByRole('button', { name: 'Choose color theme', exact: true }).click()
  await page.getByRole('menuitemradio', { name: 'Dark', exact: true }).click()
  const title = await page.title()
  const crumbs = await page.getByRole('navigation', { name: 'Breadcrumb', exact: true }).innerText()
  await page.getByRole('link', { name: 'Create account', exact: true }).click()
  const drawer = page.getByRole('dialog', { name: 'Create account', exact: true })
  await expect(drawer).toBeVisible()
  expect(await page.title()).toBe(title)
  expect(await page.getByRole('navigation', { name: 'Breadcrumb', exact: true }).innerText()).toBe(crumbs)
  const name = drawer.getByRole('textbox', { name: /^Name/ })
  await expect(name).toBeFocused()
  await name.fill('Unsaved reserve')
  await page.goBack()
  await expect(drawer).toHaveCount(0)
  for (const action of ['Escape', 'Close', 'Cancel']) {
    await page.getByRole('link', { name: 'Create account', exact: true }).click()
    await name.fill('Unsaved reserve')
    if (action === 'Escape') await page.keyboard.press('Escape')
    else if (action === 'Close') await drawer.getByRole('button', { name: 'Close', exact: true }).click()
    else await drawer.getByRole('link', { name: 'Cancel', exact: true }).click()
    await expect(drawer).toHaveCount(0)
    expect(new URL(page.url()).searchParams.get('search')).toBe('checking')
    expect(new URL(page.url()).searchParams.get('sort')).toBe('balance')
  }
  expect(prompts).toEqual([])
  await page.getByRole('link', { name: 'Create account', exact: true }).click()
  await drawer.getByRole('textbox', { name: /^Name/ }).fill('Operating checking')
  const create = drawer.getByRole('button', { name: 'Create', exact: true })
  await create.click()
  await expect(create).toBeDisabled()
  await expect(create.locator('.animate-spin')).toBeVisible()
  await expect(drawer.getByRole('textbox', { name: /^Name/ })).toHaveValue('Operating checking')
  expect(await page.title()).toBe(title)
  expect(await page.getByRole('navigation', { name: 'Breadcrumb', exact: true }).innerText()).toBe(crumbs)
  await expect(page.locator('html')).toHaveClass(/dark/)
  expect(prompts).toEqual([])
})

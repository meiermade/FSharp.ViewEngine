test('SideNav retains independent nested choices through enhanced navigation, history and refresh @cross-browser', async ({ page }) => {
  await page.goto('/examples/specification/transactions/view-transactions')
  await page.evaluate(() => { document.documentElement.dataset.navigationSession = 'retained' })
  const sidebar = page.locator('#template-desktop-navigation')
  const toggle = (name: string) => sidebar.getByLabel(`Toggle ${name} section`, { exact: true })
  await expect(toggle('Transactions')).toHaveAttribute('aria-expanded', 'true')
  await toggle('Architecture').click()
  await toggle('Solution').focus()
  await page.keyboard.press('Enter')
  await sidebar.getByRole('link', { name: 'Ledger.Domain', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1, name: 'Ledger.Domain', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-navigation-session', 'retained')
  for (const name of ['Transactions', 'Architecture', 'Solution']) {
    await expect(toggle(name)).toHaveAttribute('aria-expanded', 'true')
  }
  await page.goBack()
  await expect(page.getByRole('heading', { level: 1, name: 'View transactions', exact: true })).toBeVisible()
  await expect(toggle('Architecture')).toHaveAttribute('aria-expanded', 'true')
  await page.goForward()
  await expect(page.getByRole('heading', { level: 1, name: 'Ledger.Domain', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-navigation-session', 'retained')
  await toggle('Transactions').click()
  await toggle('Solution').focus()
  await page.keyboard.press('Space')
  await page.reload()
  await expect(toggle('Transactions')).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle('Solution')).toHaveAttribute('aria-expanded', 'false')
  await expect(toggle('Architecture')).toHaveAttribute('aria-expanded', 'true')
  await expect(sidebar.getByRole('link', { name: 'Ledger.Domain', exact: true, includeHidden: true })).toHaveAttribute('aria-current', 'page')
})

test('SideNav aligns plain items at every depth and retains guide gutters @cross-browser', async ({ page }) => {
  await page.goto('/components/side-nav')
  const nav = page.locator('#structure-navigation')
  await expect(nav.getByRole('link', { name: 'Button', exact: true })).toBeVisible()
  const geometry = await nav.evaluate(el => {
    const links = [...el.querySelectorAll('a')]
    const documentation = el.querySelector('summary[aria-label="Toggle Documentation section"]')!
    const components = el.querySelector('summary[aria-label="Toggle Components section"]')!
    const edge = (summary: Element) => {
      const svg = summary.querySelector('svg')!, box = svg.querySelector('path')!.getBBox()
      return Math.min(...[[box.x, box.y], [box.x + box.width, box.y], [box.x, box.y + box.height], [box.x + box.width, box.y + box.height]].map(([x, y]) => new DOMPoint(x, y).matrixTransform(svg.getScreenCTM()!).x))
    }
    const labelX = (name: string) => el.querySelector(`a[aria-label="${name}"]`)!.firstElementChild!.getBoundingClientRect().left
    const guides = [...el.querySelectorAll('details[open]')].map(details => {
      const svg = details.querySelector(':scope > summary svg')! as SVGSVGElement
      const ul = details.querySelector(':scope > ul')!, box = ul.getBoundingClientRect(), border = parseFloat(getComputedStyle(ul).borderLeftWidth)
      const center = new DOMPoint(10, 10).matrixTransform(svg.getScreenCTM()!).x
      return { alignment: Math.abs(box.left + border / 2 - center), gutters: [...ul.children].map(li => li.querySelector('summary, a')!).map(row => row.getBoundingClientRect().left - box.left - border) }
    })
    return { insets: links.map(link => getComputedStyle(link).paddingLeft), root: Math.abs(labelX('Home') - edge(documentation)), nested: Math.abs(labelX('Specification') - edge(components)), guides }
  })
  expect(new Set(geometry.insets).size).toBe(1)
  expect(geometry.root).toBeLessThan(0.5)
  expect(geometry.nested).toBeLessThan(0.5)
  for (const guide of geometry.guides) {
    expect(guide.alignment).toBeLessThan(0.5)
    for (const gutter of guide.gutters) expect(gutter).toBe(4)
  }
  const group = nav.getByLabel('Toggle Components section', { exact: true })
  await group.focus()
  await page.keyboard.press('Space')
  await expect(nav.getByRole('link', { name: 'Button', exact: true })).toBeHidden()
  await page.keyboard.press('Enter')
  await expect(nav.getByRole('link', { name: 'Button', exact: true })).toBeVisible()
})

test('filter chips toggle multiple choices, clear to unrestricted and retain focus through history @cross-browser', async ({ page }) => {
  await page.goto('/examples/application/accounts?search=checking&sort=balance')
  const add = page.getByRole('button', { name: 'Add filter', exact: true })
  expect((await add.boundingBox())!.height).toBe(32)
  expect((await add.locator('svg').boundingBox())!.width).toBe(14)
  await add.click()
  await page.getByRole('menuitem', { name: 'Type', exact: true }).click()
  const group = page.getByRole('group', { name: 'Type filter', exact: true })
  const trigger = group.getByRole('button', { name: 'Type filter values', exact: true })
  const asset = group.getByRole('menuitemcheckbox', { name: 'Asset', exact: true })
  const liability = group.getByRole('menuitemcheckbox', { name: 'Liability', exact: true })
  const clear = group.getByRole('menuitem', { name: 'Clear selection', exact: true })
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(clear).toBeDisabled()
  await expect(asset).toHaveAttribute('aria-checked', 'false')
  const remove = group.getByRole('button', { name: 'Remove Type filter', exact: true })
  const label = group.getByText('Type', { exact: true })
  const [labelBox, dropdownBox, removeBox] = await Promise.all([label.boundingBox(), trigger.boundingBox(), remove.boundingBox()])
  expect(Math.abs(labelBox!.x + labelBox!.width - dropdownBox!.x)).toBeLessThanOrEqual(1)
  expect(Math.abs(dropdownBox!.x + dropdownBox!.width - removeBox!.x)).toBeLessThanOrEqual(1)
  expect(labelBox!.height).toBe(dropdownBox!.height)
  expect(dropdownBox!.height).toBe(removeBox!.height)
  await expect(trigger).toHaveText('Any')
  await expect(trigger).toHaveCSS('border-top-left-radius', '0px')
  await expect(trigger).toHaveCSS('border-top-right-radius', '0px')
  await expect(remove).toHaveCSS('border-top-left-radius', '0px')
  await expect(group.getByRole('menuitemcheckbox', { name: /All/ })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Operating checking', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(trigger).toBeFocused()
  await expect(group).toBeVisible()
  await page.reload()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await trigger.press('ArrowDown')
  await asset.press('Space')
  await expect(page).toHaveURL(url => url.searchParams.get('accountType') === 'Asset')
  await expect(asset).toBeFocused()
  await expect(asset).toHaveAttribute('aria-checked', 'true')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await liability.press('Enter')
  await expect(page).toHaveURL(url => url.searchParams.get('accountType') === 'Asset,Liability')
  await expect(liability).toBeFocused()
  await expect(trigger).toHaveText('Asset, Liability')
  await expect(liability).toHaveAttribute('aria-checked', 'true')
  await group.getByRole('menuitemcheckbox', { name: 'Equity', exact: true }).click()
  await expect(trigger).toHaveText('3 selected')
  await clear.click()
  await expect(page).toHaveURL(url => url.searchParams.get('accountType') === 'all')
  await expect(trigger).toHaveText('Any')
  await expect(trigger).toBeFocused()
  await expect(group).toBeVisible()
  await group.getByRole('button', { name: 'Remove Type filter', exact: true }).click()
  await expect(group).toHaveCount(0)
  await page.goBack()
  await expect(group).toBeVisible()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  expect(new URL(page.url()).searchParams.get('search')).toBe('checking')
  expect(new URL(page.url()).searchParams.get('sort')).toBe('balance')
})

test('dismissed filter menus stay closed when an in-flight result arrives', async ({ page }) => {
  await page.goto('/examples/application/accounts?filters=accountType')
  const trigger = page.getByRole('button', { name: 'Type filter values', exact: true })
  for (const dismissal of ['Escape', 'outside']) {
    let release!: () => void
    let requested!: () => void
    const pending = new Promise<void>(resolve => { requested = resolve })
    const ready = new Promise<void>(resolve => { release = resolve })
    await page.route('**/examples/application/accounts?**', async route => {
      requested()
      await ready
      await route.continue()
    })
    try {
      await trigger.click()
      await page.getByRole('menuitemcheckbox', { name: 'Asset', exact: true }).click()
      await pending
      if (dismissal === 'Escape') await page.keyboard.press('Escape')
      else await page.getByRole('heading', { name: 'Accounts', exact: true, level: 1 }).click()
      await expect(trigger).toHaveAttribute('aria-expanded', 'false')
      release()
      await expect(trigger).toHaveText(dismissal === 'Escape' ? 'Asset' : 'Any')
      await expect(page.locator('#main-content')).toBeFocused()
      await expect(trigger).toHaveAttribute('aria-expanded', 'false')
    } finally {
      release()
      await page.unroute('**/examples/application/accounts?**')
    }
  }
})


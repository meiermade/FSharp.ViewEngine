import { expect, test, type Locator } from '@playwright/test'

async function expectSelection(form: Locator, start: string, minutes: number) {
  await expect(form.locator('[data-time-value]')).toHaveValue(start)
  await expect(form.locator('[data-time-input]')).toHaveValue(start)
  await expect(form.locator('[data-range-selection]')).toHaveAttribute('data-valid', 'true')
  await expect.poll(() => form.evaluate(el => [...new FormData(el as HTMLFormElement).entries()])).toEqual([
    ['selection.start', start], ['selection.minutes', String(minutes)],
  ])
  expect(await form.evaluate(el => (el as HTMLFormElement).checkValidity())).toBe(true)
}

test('installed ranges share a midnight-based 45-minute grid with picker and background geometry', async ({ page }) => {
  await page.goto('/')
  const form = page.locator('#generated-step-range-form')
  const range = form.locator('fve-calendar-range')
  const move = range.getByRole('button', { name: 'Move selected time range', exact: true })
  await expect(form.locator('[data-time-input]')).toBeVisible()
  await expectSelection(form, '09:00', 45)
  await expect(form.locator('[data-time-value]')).toHaveAttribute('min', '08:15')
  await expect(form.locator('[data-time-value]')).toHaveAttribute('max', '17:15')
  const geometry = await range.evaluate(el => {
    const grid = el.querySelector('.fve-calendar-events')!.getBoundingClientRect()
    const first = el.querySelector('[data-range-start]')!.getBoundingClientRect()
    return { offset: first.top - grid.top, height: first.height }
  })
  expect(geometry.offset).toBeCloseTo(20, 0)
  expect(geometry.height).toBeCloseTo(60, 0)
  await move.press('Home')
  await expectSelection(form, '08:15', 45)
  await move.press('ArrowDown')
  await expectSelection(form, '09:00', 45)
  await move.press('End')
  await expectSelection(form, '17:15', 45)
  await move.press('ArrowUp')
  await expectSelection(form, '16:30', 45)
  await range.locator('[data-range-start="585"]').click()
  await expectSelection(form, '09:45', 45)
  await form.getByRole('combobox', { name: 'Start time', exact: true }).fill('10:30')
  await form.getByRole('combobox', { name: 'Start time', exact: true }).press('Tab')
  await expectSelection(form, '10:30', 45)
})

test('installed ranges retain valid submitted starts when uneven durations grow near closing', async ({ page }) => {
  await page.goto('/')
  const form = page.locator('#generated-duration-range-form')
  const range = form.locator('fve-calendar-range')
  const move = range.getByRole('button', { name: 'Move selected time range', exact: true })
  await expect(form.locator('[data-time-input]')).toBeVisible()
  await expectSelection(form, '21:30', 30)
  await move.press('Shift+ArrowDown')
  await expectSelection(form, '21:00', 45)
  await expect(form.locator('[data-time-value]')).toHaveAttribute('max', '21:00')
  await move.press('ArrowUp')
  await expectSelection(form, '20:30', 45)
  await move.press('End')
  await expectSelection(form, '21:00', 45)
  await move.press('ArrowUp')
  await move.scrollIntoViewIfNeeded()
  const handle = (await move.boundingBox())!
  const grid = (await range.locator('.fve-calendar-events').boundingBox())!
  await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
  await page.mouse.down()
  await page.mouse.move(handle.x + handle.width / 2, grid.y + grid.height - 2, { steps: 4 })
  await page.mouse.up()
  await expectSelection(form, '21:00', 45)
  await form.getByRole('button', { name: 'Reset range', exact: true }).click()
  await expectSelection(form, '21:30', 30)
  await form.getByRole('combobox', { name: 'Duration', exact: true }).click()
  await page.getByRole('option', { name: '45 minutes', exact: true }).click()
  await expectSelection(form, '21:00', 45)
  const start = form.getByRole('combobox', { name: 'Start time', exact: true })
  await start.fill('not a time')
  await start.press('Tab')
  await expect(form.locator('[data-time-value]')).toHaveValue('')
  await form.getByRole('combobox', { name: 'Duration', exact: true }).click()
  await page.getByRole('option', { name: '30 minutes', exact: true }).click()
  await expect(start).toHaveValue('not a time')
  await expect(form.locator('[data-time-value]')).toHaveValue('')
  expect(await form.evaluate(el => (el as HTMLFormElement).checkValidity())).toBe(false)
})

namespace FSharp.ViewEngine.Cli

open System
open System.Diagnostics
open System.IO
open System.Text.Json
open System.Text.Json.Nodes

[<RequireQualifiedAccess>]
module Frontend =
    let defaults =
        { Root = "."; Package = "package.json"; Entry = "js/app.js"; Script = "wwwroot/js/app.js"
          InputCss = "input.css"; OutputCss = "wwwroot/css/output.css"
          ManualModules = [||]; External = [||]; Entries = [||] }

    let private items values = Option.ofObj values |> Option.defaultValue [||]

    let private directories (configRoot:string) (config: FrontendConfiguration) =
        // A UI library can supply browser assets to a sibling web host.
        let root =
            if config.Root = "." then configRoot
            else
                let parent, path =
                    if config.Root.StartsWith("../", StringComparison.Ordinal) then Path.GetDirectoryName configRoot, config.Root.Substring 3
                    else configRoot, config.Root
                match Validation.consumerPaths parent [path] with
                | Ok () -> Path.Combine(parent, path)
                | Error message -> invalidOp message
        let generated = Path.Combine(Path.GetDirectoryName config.Entry, "fve-imports.js").Replace('\\', '/')
        let paths = [config.Package; config.Entry; config.Script; config.InputCss; config.OutputCss; generated]
        match Validation.consumerPaths root paths, Validation.consumerPaths configRoot (items config.Entries) with
        | Error message, _ | _, Error message -> invalidOp message
        | Ok (), Ok () when (Set.ofList paths).Count <> paths.Length -> invalidOp "Frontend input and output paths must be distinct."
        | Ok (), Ok () when Path.GetExtension config.Script <> ".js" -> invalidOp "The compiled script path must end in .js."
        | Ok (), Ok () -> root, fun path -> Path.Combine(root, path)

    let validate configRoot config = directories configRoot config |> ignore

    let private relative directory file =
        let path = Path.GetRelativePath(directory, file).Replace('\\', '/')
        if path.StartsWith(".", StringComparison.Ordinal) then path else "./" + path

    let private create file content = if not (File.Exists file) then Text.writeAtomic file content

    let refreshImports configRoot (config: FrontendConfiguration) (modules: string array) =
        let _, path = directories configRoot config
        let entry = path config.Entry
        let generated = Path.Combine(Path.GetDirectoryName entry, "fve-imports.js")
        let lines =
            modules |> Array.distinct |> Array.filter (fun file -> not (Array.contains (Path.GetFileName file) (items config.ManualModules))) |> Array.map (fun file ->
                "import " + JsonSerializer.Serialize(relative (Path.GetDirectoryName generated) (Path.GetFullPath(Path.Combine(configRoot, file)))) + ";")
        Text.writeAtomic generated (String.concat "\n" (Array.append [|"// Generated by fve. Edit your app entry point, not this file."|] lines) + "\n")
        let line = "import " + JsonSerializer.Serialize(relative (Path.GetDirectoryName entry) generated) + ";"
        create entry (line + "\n")
        let existing = File.ReadAllText entry
        if not (existing.Contains(relative (Path.GetDirectoryName entry) generated, StringComparison.Ordinal)) then
            Text.writeAtomic entry (line + "\n" + existing)

    let private toolPackages = ["tailwindcss", ScriptBuild.TailwindVersion; "@tailwindcss/cli", ScriptBuild.TailwindVersion; "esbuild", ScriptBuild.EsbuildVersion]

    let preparePackages configRoot config initializing modules =
        try
            let _, path = directories configRoot config
            let package = path config.Package
            let json = if File.Exists package then JsonNode.Parse(File.ReadAllText package).AsObject() else JsonObject()
            let current =
                [ for group in ["dependencies"; "devDependencies"] do
                    match json[group] with
                    | :? JsonObject as dependencies -> yield! dependencies
                    | null -> ()
                    | _ -> invalidOp $"'{group}' in {package} must be an object." ]
            let browserPackages = ScriptBuild.browserPackages modules
            for name, version in browserPackages do
                for item in current do
                    if item.Key = name && (isNull item.Value || item.Value.ToString() <> version) then
                        invalidOp $"'{package}' already specifies {name} with a different version. Set it to {version} and retry."
            let missing =
                (if initializing then toolPackages @ browserPackages else browserPackages)
                |> List.filter (fun (name, _) -> current |> List.forall (fun item -> item.Key <> name))
            Ok (fun () ->
                if not missing.IsEmpty then
                    let dependencies =
                        match json["devDependencies"] with
                        | :? JsonObject as deps -> deps
                        | _ -> let deps = JsonObject() in json["devDependencies"] <- deps; deps
                    for name, version in missing do dependencies[name] <- JsonValue.Create version
                    Text.writeAtomic package (json.ToJsonString(JsonSerializerOptions(WriteIndented = true)) + "\n"))
        with error -> Error error.Message

    let initialize configRoot config modules =
        match preparePackages configRoot config true modules with
        | Ok write -> write ()
        | Error message -> invalidOp message
        let _, path = directories configRoot config
        let css = path config.InputCss
        let components = relative (Path.GetDirectoryName css) (Path.Combine(configRoot, "Components"))
        create css ($"@import \"tailwindcss\";\n@source \"{components}/**/*.fs\";\n@source \"{components}/Assets/*.js\";\n")
        refreshImports configRoot config modules

    let compile configRoot config watch =
        let root, path = directories configRoot config
        let modules = Path.Combine(Path.GetDirectoryName(path config.Package), "node_modules")
        let tool file =
            let path = Path.Combine(modules, file)
            if not (File.Exists path) then invalidOp $"'{path}' is missing. Run npm install beside {config.Package}."
            path
        let command args =
            let start = ProcessStartInfo("node", WorkingDirectory = root, UseShellExecute = false)
            for arg in args do start.ArgumentList.Add arg
            start
        let css = command (tool "@tailwindcss/cli/dist/index.mjs" :: ScriptBuild.stylesheetArguments (path config.InputCss) (path config.OutputCss) watch)
        let entry name file = dict ["in", file; "out", name]
        let entryPoints = Array.append [| entry (Path.GetFileNameWithoutExtension config.Script) (path config.Entry) |]
                            (items config.Entries |> Array.map (fun file -> entry (Path.GetFileNameWithoutExtension file) (Path.GetFullPath(Path.Combine(configRoot,file)))))
        let options = JsonSerializer.Serialize({| entryPoints = entryPoints; bundle = true; format = "esm"; minify = true; splitting = true; outdir = Path.GetDirectoryName(path config.Script); external = items config.External; nodePaths = [|modules|] |})
        let js = command (ScriptBuild.bundleArguments (tool "esbuild/lib/main.js") options watch)
        use styles = Process.Start css
        use scripts = Process.Start js
        let stop (child: Process) = if not child.HasExited then try child.Kill true with :? InvalidOperationException -> ()
        let cancelled = ConsoleCancelEventHandler(fun _ event -> event.Cancel <- true; stop styles; stop scripts)
        Console.CancelKeyPress.AddHandler cancelled
        try
            if watch then
                Threading.Tasks.Task.WhenAny(styles.WaitForExitAsync(), scripts.WaitForExitAsync()).GetAwaiter().GetResult() |> ignore
            else
                styles.WaitForExit()
                scripts.WaitForExit()
            if (styles.HasExited && styles.ExitCode <> 0) || (scripts.HasExited && scripts.ExitCode <> 0) then
                invalidOp "Frontend compilation failed."
        finally
            Console.CancelKeyPress.RemoveHandler cancelled
            stop styles
            stop scripts
